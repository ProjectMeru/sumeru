package importgen

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"sumeru/core/modelmeta"
)

func buildORMModelsGo(module string, types []string) string {
	if 0 == len(types) {
		return ""
	}
	var b strings.Builder
	b.WriteString("// Code generated by sumeru-import-gen; DO NOT EDIT.\n\npackage ormmodels\n\nimport (\n\t\"sumeru/core/modelreg\"\n\t\"sumeru/core/orm\"\n)\n\nfunc init() {\n\tmodelreg.MustRegister(\"")
	b.WriteString(module)
	b.WriteString("\",\n")
	for _, t := range types {
		b.WriteString("\t\t&orm.")
		b.WriteString(t)
		b.WriteString("{},\n")
	}
	b.WriteString("\t)\n}\n")
	return b.String()
}

func buildPackageModelsGo(module string, types []string, packageName string, binds []computeBind) string {
	if 0 == len(types) {
		return ""
	}
	if packageName == "" {
		packageName = "models"
	}
	var b strings.Builder
	b.WriteString("// Code generated by sumeru-import-gen; DO NOT EDIT.\n\npackage ")
	b.WriteString(packageName)
	b.WriteString("\n\nimport \"sumeru/core/sdk\"\n\nfunc init() {\n")
	b.WriteString("\tsdk.MustRegister(\"")
	b.WriteString(module)
	b.WriteString("\",\n")
	for _, t := range types {
		b.WriteString("\t\t&")
		b.WriteString(t)
		b.WriteString("{},\n")
	}
	b.WriteString("\t)\n")
	for _, bind := range binds {
		fmt.Fprintf(&b, "\tsdk.BindCompute(%q, %q, %s)\n", bind.Model, bind.Field, bind.Func)
	}
	b.WriteString("}\n")
	return b.String()
}

func writeAddonModelFiles(addonRoot, module string) error {
	if err := writePackageModels(addonRoot, module, filepath.Base(addonRoot)); err != nil {
		return err
	}
	for _, sub := range []string{"models", "wizard"} {
		if err := writePackageModels(filepath.Join(addonRoot, sub), module, ""); err != nil {
			return err
		}
	}
	return nil
}

func writePackageModels(dir, module, packageName string) error {
	info, err := os.Stat(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if !info.IsDir() {
		return nil
	}
	if packageName == "" {
		packageName = packageNameForDir(dir)
	}
	body, err := packageModelsBody(dir, module, packageName)
	if err != nil {
		return err
	}
	if body == "" {
		return nil
	}
	dest := filepath.Join(dir, "zmodels.go")
	if err := os.WriteFile(dest, []byte(body), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", dest, err)
	}
	return nil
}

func packageModelsBody(dir, module, packageName string) (string, error) {
	models, err := parseDirModels(dir)
	if err != nil {
		return "", err
	}
	var types []string
	var binds []computeBind
	for _, m := range models {
		if m.ModelName == "-" {
			continue
		}
		types = append(types, m.GoName)
		binds = append(binds, m.Computes...)
	}
	sort.Strings(types)
	sort.Slice(binds, func(i, j int) bool {
		if binds[i].Model != binds[j].Model {
			return binds[i].Model < binds[j].Model
		}
		if binds[i].Field != binds[j].Field {
			return binds[i].Field < binds[j].Field
		}
		return binds[i].Func < binds[j].Func
	})
	return buildPackageModelsGo(module, types, packageName, binds), nil
}

func writeORMModelsRegistration(ormDir, ormmodelsDir, module string) error {
	types, err := scanPackageForModels(ormDir)
	if err != nil {
		return nil
	}
	if 0 == len(types) {
		return nil
	}

	body := buildORMModelsGo(module, types)
	if err := os.MkdirAll(ormmodelsDir, 0o755); err != nil {
		return err
	}
	dest := filepath.Join(ormmodelsDir, "zmodels.go")
	if err := os.WriteFile(dest, []byte(body), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", dest, err)
	}
	return nil
}

func writeORMZRefs(ormDir string) error {
	used, err := scanUsedRelationTypes(ormDir)
	if err != nil {
		return err
	}
	local, err := scanPackageForModels(ormDir)
	if err != nil {
		return err
	}
	localSet := map[string]struct{}{}
	for _, name := range local {
		localSet[name] = struct{}{}
	}

	var names []string
	for name := range used {
		if _, ok := localSet[name]; ok {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)

	zrefsPath := filepath.Join(ormDir, "zrefs.go")
	if 0 == len(names) {
		_ = os.Remove(zrefsPath)
		return nil
	}

	var b strings.Builder
	b.WriteString("// Code generated by sumeru-import-gen; DO NOT EDIT.\n\npackage orm\n\nimport \"sumeru/core/modelmeta\"\n\n")
	for _, name := range names {
		technical := modelmeta.ModelNameFromGo(name)
		fmt.Fprintf(&b, "// %s → %s\n", name, technical)
		fmt.Fprintf(&b, "type %s struct {\n\tmodelmeta.ModelMeta `sumeru:\"model=%s\"`\n}\n\n", name, technical)
	}
	return os.WriteFile(zrefsPath, []byte(b.String()), 0o644)
}
